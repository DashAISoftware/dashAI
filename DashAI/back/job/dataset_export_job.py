"""Job for publishing a DashAI dataset to an external platform."""

import logging
import shutil
import tempfile
from pathlib import Path
from typing import TYPE_CHECKING

from kink import di, inject
from sqlalchemy import exc

from DashAI.back.core.enums.status import DatasetExportStatus, DatasetStatus
from DashAI.back.dependencies.database.models import Dataset, DatasetExport
from DashAI.back.job.base_job import BaseJob, JobError

if TYPE_CHECKING:
    from sqlalchemy.orm import sessionmaker

log = logging.getLogger(__name__)

#: Export phase reported by ``BaseDatasetExporter.export`` mapped to the
#: status stored on the ``dataset_export`` row.
_STEP_STATUS = {
    "prepare": DatasetExportStatus.PREPARING,
    "upload": DatasetExportStatus.UPLOADING,
}


def export_temp_dir(export_id: int) -> Path:
    """Return the scratch directory used by one export.

    It is derived from the export id so the consumer process can find and
    remove it in :meth:`DatasetExportJob.on_cancel` after killing the worker.

    Parameters
    ----------
    export_id : int
        Id of the ``dataset_export`` row.

    Returns
    -------
    Path
        Directory for the files generated by the exporter.
    """
    return Path(tempfile.gettempdir()) / "dashai_exports" / str(export_id)


class DatasetExportJob(BaseJob):
    """Job that publishes a dataset with a registered DatasetExporter.

    Parameters
    ----------
    kwargs : dict
        - export_id: int (``dataset_export`` row id)
        - dataset_name: str, optional (only used for the job name)
    """

    @inject
    def set_status_as_delivered(
        self, session_factory: "sessionmaker" = lambda di: di["session_factory"]
    ) -> None:
        """No-op: the export row is created as pending, which means delivered."""

    @inject
    def set_status_as_error(
        self, session_factory: "sessionmaker" = lambda di: di["session_factory"]
    ) -> None:
        """Set the export status as error.

        The queue also calls this from its own copy of the job, which lacks
        the message the worker stored, so an existing message is kept. A
        published export is never downgraded to error.

        Parameters
        ----------
        session_factory : sessionmaker
            Factory producing a SQLAlchemy session.
        """
        export_id: int = self.kwargs["export_id"]
        error_msg: str = self.kwargs.get("_error_message", "")
        with session_factory() as db:
            row: DatasetExport = db.get(DatasetExport, export_id)
            if row is None or row.status == DatasetExportStatus.PUBLISHED:
                return
            row.status = DatasetExportStatus.ERROR
            row.error_message = error_msg or row.error_message or "Export interrupted"
            try:
                db.commit()
            except exc.SQLAlchemyError as e:
                log.exception(e)

    def on_cancel(self) -> None:
        """Remove the scratch files of a cancelled or killed export.

        A cancel that lands during the upload may still leave the dataset
        published on the platform; the platform has the final say.
        """
        try:
            shutil.rmtree(export_temp_dir(self.kwargs["export_id"]), ignore_errors=True)
        except Exception:
            log.exception("on_cancel cleanup failed for DatasetExportJob")

    def get_job_name(self) -> str:
        """Get a descriptive name for the job."""
        name = self.kwargs.get("dataset_name", "")
        return f"Dataset export: {name}" if name else "Dataset export"

    def run(self) -> None:
        from DashAI.back.dataloaders.classes.dashai_dataset import load_dataset

        component_registry = di["component_registry"]
        session_factory = di["session_factory"]

        export_id: int = self.kwargs["export_id"]
        temp_dir = export_temp_dir(export_id)

        def set_status(status: DatasetExportStatus) -> None:
            with session_factory() as db:
                row = db.get(DatasetExport, export_id)
                row.status = status
                db.commit()

        try:
            with session_factory() as db:
                row: DatasetExport = db.get(DatasetExport, export_id)
                if row is None:
                    raise JobError(f"Dataset export {export_id} not found.")
                row.huey_id = self.kwargs.get("huey_id")
                db.commit()
                exporter_name = row.exporter_name
                params = dict(row.params or {})

                if row.dataset_id is None:
                    raise JobError("The dataset of this export no longer exists.")
                dataset_row = db.get(Dataset, row.dataset_id)
                if dataset_row is None:
                    raise JobError("The dataset of this export no longer exists.")
                if dataset_row.status != DatasetStatus.FINISHED:
                    raise JobError(f"Dataset '{dataset_row.name}' is not ready.")
                dataset_path = Path(dataset_row.file_path) / "dataset"

            try:
                exporter_entry = component_registry[exporter_name]
            except KeyError as e:
                raise JobError(f"DatasetExporter '{exporter_name}' not found.") from e
            if exporter_entry.get("type") not in (None, "DatasetExporter"):
                raise JobError(f"'{exporter_name}' is not a DatasetExporter.")
            exporter = exporter_entry["class"]()

            self.report_progress(0.1, "Loading dataset")
            dataset = load_dataset(str(dataset_path))

            def on_step(step: str) -> None:
                set_status(_STEP_STATUS[step])
                if step == "prepare":
                    self.report_progress(0.3, "Preparing dataset")
                else:
                    self.report_progress(0.6, "Uploading dataset")

            temp_dir.mkdir(parents=True, exist_ok=True)
            result = exporter.export(dataset, params, str(temp_dir), on_step=on_step)

            with session_factory() as db:
                row = db.get(DatasetExport, export_id)
                row.status = DatasetExportStatus.PUBLISHED
                row.remote_id = result.remote_id
                row.remote_url = result.url
                row.error_message = None
                try:
                    db.commit()
                except exc.SQLAlchemyError as e:
                    log.exception(e)
                    raise JobError("DB error saving the export result.") from e

            self.report_progress(1.0, "Published")
            log.debug("Dataset export %d published at %s", export_id, result.url)

        except Exception as e:
            err_msg = str(e)
            log.error("Dataset export %d failed: %s", export_id, err_msg)
            self.kwargs["_error_message"] = err_msg
            self.set_status_as_error()
            if isinstance(e, JobError):
                raise
            raise JobError(err_msg) from e

        finally:
            shutil.rmtree(temp_dir, ignore_errors=True)
